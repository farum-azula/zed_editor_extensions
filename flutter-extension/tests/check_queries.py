"""Checks the languages' tree-sitter queries against the grammars: Dart's, the commit
extension.toml pins, Dartdoc's, tree-sitter-dartdoc in this extension, and those of the languages
of examples (Java, Rust, JavaScript, TypeScript, Python), the versions Zed and its Java extension use.

- every query of languages/ compiles: Zed drops a query that does not, and with highlights.scm
  that is all of the file's highlighting;
- tests/queries/highlights.dart parses without errors (it uses the newest Dart syntax the grammar
  is pinned for), and highlights.scm gives each place marked in it the capture expected;
- tree-sitter-dartdoc/src is what its grammar.js generates, and its corpus (test/corpus) passes;
- in tests/queries/doc_comments.dart, built into layers the way Zed builds them (one Dartdoc layer
  for all the `///` comments, a layer for each code block in them, of the language its fence
  names), the code blocks parse without errors and each place marked gets the capture expected:
  the language's in a code block, `comment.documentation` elsewhere;
- the languages of examples (DOC_LANGUAGES), languages/dartdoc-<name>, are what --update writes:
  the language's highlights.scm, each capture suffixed `.dartdoc`, and nothing else, so that the
  code of examples stays out of the outline and gets no run button; languages/dartdoc/injections.scm
  sends each fence's code to its language;
- the Farum Azula themes (../theme-extension) set examples apart: each capture of those languages
  has a style of its own, the colors of the capture it is suffixed to, darkened (DOC_BRIGHTNESS),
  so that an example is not taken for the code around it; fences and blocks of other languages
  (`dartdoc.code`) look like the comment.

`--update` writes languages/dartdoc-<name>, languages/dartdoc/injections.scm, and those styles of
the themes, then checks.

In the fixtures, a comment line with `^` (or `<-`, for its own first column) names the capture
expected at that column of the line above it; a capture it falls back from counts too
(`keyword.definition` is a `keyword`).

    python3 tests/check_queries.py [--update]       # needs cargo, git and npx
"""

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECKER = ROOT / "tests" / "queries"
LANGUAGES = ROOT / "languages"
LANGUAGE = LANGUAGES / "dart"
DARTDOC = ROOT / "tree-sitter-dartdoc"
# The tree-sitter CLI that generated tree-sitter-dartdoc/src.
TREE_SITTER_CLI = "0.27.1"
THEMES = ROOT.parent / "theme-extension" / "themes" / "farum-azula.json"
DOC_SUFFIX = ".dartdoc"
SOURCES = ROOT / "tests" / "doc_languages"

# The languages of examples: directory, language name, grammar, the highlights.scm it is made from,
# and the fence names that pick it (the Dart one is also the language of a fence without a name,
# as for dartdoc). Java's grammar is the Java extension's; the others come with Zed (JavaScript is
# Zed's `tsx`).
DOC_LANGUAGES = [
    ("dartdoc-dart", "Dartdoc Dart", "dart", LANGUAGE / "highlights.scm", ["dart", "Dart"]),
    ("dartdoc-java", "Dartdoc Java", "java", SOURCES / "java.scm", ["java", "Java"]),
    ("dartdoc-rust", "Dartdoc Rust", "rust", SOURCES / "rust.scm", ["rust", "rs"]),
    ("dartdoc-javascript", "Dartdoc JavaScript", "tsx", SOURCES / "javascript.scm", ["js", "javascript", "jsx"]),
    ("dartdoc-typescript", "Dartdoc TypeScript", "typescript", SOURCES / "typescript.scm", ["ts", "typescript"]),
    ("dartdoc-python", "Dartdoc Python", "python", SOURCES / "python.scm", ["python", "py"]),
]

failures = []


def check(ok, what):
    print(("ok    " if ok else "FAIL  ") + what)
    if not ok:
        failures.append(what)


def pinned_grammar():
    manifest = (ROOT / "extension.toml").read_text()
    section = manifest[manifest.index("[grammars.dart]"):]
    repository = re.search(r'^repository = "([^"]+)"', section, re.M).group(1)
    commit = re.search(r'^(?:commit|rev) = "([^"]+)"', section, re.M).group(1)
    return repository, commit


def expectations(fixture):
    """(row, column, capture) for each `^` / `<-` mark, 1-based."""
    expected = []
    code_row = None
    for row, line in enumerate(fixture.splitlines(), 1):
        mark = re.match(r"\s*//\s*(<-|\^)", line)
        if mark and code_row is not None:
            column = 1 if mark.group(1) == "<-" else line.index("^") + 1
            expected.append((code_row, column, line.split(mark.group(1), 1)[1].strip()))
        elif not line.lstrip().startswith("//") or line.lstrip().startswith("///"):
            code_row = row
    return expected


GENERATED = "Generated by `python3 tests/check_queries.py --update`"

# A query's strings and comments, and its captures outside them.
QUERY_TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|;[^\n]*|@([A-Za-z][\w.]*)')


def suffixed(query):
    """`query` with each capture suffixed `.dartdoc` (not an `@` in a string or a comment)."""
    return QUERY_TOKEN.sub(lambda m: m.group(0) + DOC_SUFFIX if m.group(1) else m.group(0), query)


def captures_of(query):
    return {m.group(1) for m in QUERY_TOKEN.finditer(query) if m.group(1)}


def doc_language_files():
    """What --update writes: {path: text}."""
    files = {}
    injections = [
        "; " + GENERATED + " from DOC_LANGUAGES: the lines of a\n"
        "; code block go to the language its fence names (Dart's for a fence without a name, as for\n"
        "; dartdoc), a match per line and the block as their host, so that Zed parses a block's lines\n"
        "; together and each block apart. Fences of other languages stay comments.\n"
    ]
    for directory, name, grammar, source, fences in DOC_LANGUAGES:
        origin = source.relative_to(ROOT)
        files[LANGUAGES / directory / "config.toml"] = (
            f"# {GENERATED}: the code of examples in documentation\n"
            f"# comments (languages/dartdoc) whose fence names it. The `{grammar}` grammar with {origin}, each\n"
            "# capture suffixed `.dartdoc` (`keyword.dartdoc`, which a theme styles as `keyword` unless it\n"
            "# has a style of its own), and nothing else: no outline, runnables or tasks, so that an\n"
            "# example's declarations stay out of the outline and get no run button. Hidden, so that the\n"
            "# language there stays Dart's.\n"
            f'name = "{name}"\ngrammar = "{grammar}"\nhidden = true\n'
        )
        files[LANGUAGES / directory / "highlights.scm"] = (
            f"; {GENERATED} from {origin}:\n"
            "; the same queries, each capture suffixed `.dartdoc`. Edit that, then regenerate.\n\n"
            + suffixed(source.read_text())
        )
        names = " ".join(f'"{f}"' for f in fences)
        if grammar == "dart":
            injections.append(
                f"((code_block\n  !language\n  (code) @injection.content) @injection.host\n"
                f'  (#set! injection.language "{name}"))\n'
            )
        injections.append(
            f"((code_block\n  language: (info_string) @_language\n  (code) @injection.content) @injection.host\n"
            f"  (#any-of? @_language {names})\n"
            f'  (#set! injection.language "{name}"))\n'
        )
    files[LANGUAGES / "dartdoc" / "injections.scm"] = "\n".join(injections)
    return files


def doc_captures():
    """The captures of the languages of examples."""
    return sorted({
        capture
        for path, text in doc_language_files().items()
        if path.name == "highlights.scm"
        for capture in captures_of(text)
    })


def theme_style(syntax, capture):
    """The style Zed gives `capture`: that of the longest key it starts with, up to a dot."""
    keys = [k for k in syntax if capture == k or capture.startswith(k + ".")]
    return dict(syntax[max(keys, key=len)]) if keys else {}


# How bright the code of an example is, of the code around it: darker, toward black. (Not more
# transparent: on a transparent theme, over a light wallpaper, that is lighter.)
DOC_BRIGHTNESS = 0.6


def dimmed(color):
    """`#rrggbb[aa]` with its red, green and blue at DOC_BRIGHTNESS, its opacity as it was."""
    rgb = "".join(f"{round(int(color[i:i + 2], 16) * DOC_BRIGHTNESS):02x}" for i in (1, 3, 5))
    return f"#{rgb}{color[7:9]}"


def themed_doc_styles(theme):
    """The `.dartdoc` styles of a theme: each capture's style, its color (or the text's) dimmed."""
    syntax = theme["style"]["syntax"]
    styles = {}
    for capture in doc_captures():
        style = theme_style(syntax, capture[: -len(DOC_SUFFIX)])
        style["color"] = dimmed(style.get("color") or theme["style"]["editor.foreground"])
        styles[capture] = style
    return styles


def update():
    for path, text in doc_language_files().items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(text)
    themes = json.loads(THEMES.read_text())
    for theme in themes["themes"]:
        syntax = theme["style"]["syntax"]
        if "dartdoc.code" in syntax:
            for key in [k for k in syntax if k.endswith(DOC_SUFFIX)]:
                del syntax[key]
            syntax.update(themed_doc_styles(theme))
    THEMES.write_text(json.dumps(themes, indent=2, ensure_ascii=False) + "\n")


def main():
    if "--update" in sys.argv:
        update()
    repository, commit = pinned_grammar()
    with tempfile.TemporaryDirectory() as tmp:
        grammar = Path(tmp) / "grammar"
        subprocess.run(["git", "init", "-q", str(grammar)], check=True)
        for args in (
            ["remote", "add", "origin", repository],
            ["fetch", "-q", "--depth", "1", "origin", commit],
            ["-c", "advice.detachedHead=false", "checkout", "-q", commit],
        ):
            subprocess.run(["git", "-C", str(grammar), *args], check=True)
        subprocess.run(
            ["cargo", "build", "--quiet", "--release", "--manifest-path", str(CHECKER / "Cargo.toml")],
            env={**os.environ, "GRAMMAR_SRC": str(grammar / "src")},
            check=True,
        )
    exe = CHECKER / "target" / "release" / ("dart-queries-check" + (".exe" if sys.platform == "win32" else ""))
    print(f"== grammar {commit[:12]}")

    queries = sorted(LANGUAGES.glob("*/*.scm"))
    result = subprocess.run([exe, "compile", *map(str, queries)], capture_output=True, text=True)
    check(result.returncode == 0, f"the {len(queries)} queries compile {result.stdout.strip()}")

    fixture = CHECKER / "highlights.dart"
    result = subprocess.run([exe, "errors", str(fixture)], capture_output=True, text=True)
    check(result.returncode == 0, f"highlights.dart parses without errors {result.stdout.strip()}")

    out = subprocess.run([exe, "captures", str(LANGUAGE / "highlights.scm"), str(fixture)], capture_output=True, text=True, check=True).stdout
    captures = []
    for order, line in enumerate(out.splitlines()):
        position, name, text = line.split("\t", 2)
        row, column = map(int, position.split(":"))
        captures.append((row, column, len(text), order, name, text))

    print("== highlights")
    check_marks(fixture, [(0, *c) for c in captures])

    check_dartdoc_grammar()
    check_doc_comments(exe)
    check_runnables(exe)

    print(f"{len(failures)} check(s) failed" if failures else "all checks passed")
    sys.exit(1 if failures else 0)


def check_runnables(exe):
    """runnables.scm: a run button on every top-level main() (`dart-main`), and on a Flutter app's
    main() the Flutter run tasks too (`flutter-main`); nothing for tests, which run as a whole."""
    print("== runnables")
    query = LANGUAGE / "runnables.scm"

    def runnables(text):
        with tempfile.NamedTemporaryFile("w", suffix=".dart", delete=False) as f:
            f.write(text)
        try:
            out = subprocess.run([exe, "runnables", str(query), f.name], capture_output=True, text=True, check=True).stdout
        finally:
            os.unlink(f.name)
        return {(line.split("\t")[0], line.split("\t")[2]) for line in out.splitlines()}

    check(runnables("void main(List<String> args) {\n  print(args);\n}\n") == {("1:6", "dart-main")}, "a plain main(): dart-main, on the name")
    check(
        runnables("import 'package:flutter/material.dart';\n\nvoid main() => runApp(const App());\n") == {("3:6", "flutter-main"), ("3:6", "dart-main")},
        "a Flutter app's main(): flutter-main and dart-main",
    )
    check(runnables("import 'package:flutter_test/flutter_test.dart';\n\nvoid main() {\n  testWidgets('x', (t) async {});\n}\n") == {("3:6", "dart-main")}, "a Flutter test: only dart-main (tests run as a whole)")
    check(runnables("import 'package:test/test.dart';\n\nvoid main() {\n  group('g', () {\n    test('t', () {});\n  });\n}\n") == {("3:6", "dart-main")}, "a Dart test: only dart-main, nothing on group or test")
    check(runnables("void helper() {}\nclass A {\n  void main() {}\n}\n") == {("3:8", "dart-main")}, "only functions named main (a method named main counts too, as in Zed's other languages)")
    check(runnables("int add(int a, int b) => a + b;\n") == set(), "nothing without a main")


def check_marks(fixture, captures):
    """Checks each mark of `fixture` against `captures`: (depth, row, column, length, order, name)."""
    for row, column, expected in expectations(fixture.read_text()):
        # Of the captures over that place, those of the deepest layer, which Zed draws over the
        # others; of those, the innermost; of those, the last, as in Zed.
        over = [c for c in captures if c[1] == row and c[2] <= column < c[2] + c[3]]
        got = min(over, key=lambda c: (-c[0], c[3], -c[4]))[5] if over else None
        line = fixture.read_text().splitlines()[row - 1]
        token = re.match(r"[\w$@']+", line[column - 1:])
        label = token.group() if token else line[column - 1:column + 9]
        ok = got is not None and (got == expected or got.startswith(expected + "."))
        check(ok, f"{row}:{column} {label!r} is {expected}" + ("" if ok else f" (got {got})"))


def tree_sitter(*args, cwd):
    npx = shutil.which("npx")
    return subprocess.run(
        [npx, "--yes", f"tree-sitter-cli@{TREE_SITTER_CLI}", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
    )


def check_dartdoc_grammar():
    print("== tree-sitter-dartdoc")
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "tree-sitter-dartdoc"
        shutil.copytree(DARTDOC, copy)
        result = tree_sitter("generate", cwd=copy)
        check(result.returncode == 0, f"grammar.js generates {result.stderr.strip()}")
        stale = [
            str(p.relative_to(copy))
            for p in sorted((copy / "src").rglob("*"))
            if p.is_file() and p.read_bytes() != (DARTDOC / p.relative_to(copy)).read_bytes()
        ]
        check(not stale, f"src/ is what grammar.js generates (regenerate: npx tree-sitter-cli@{TREE_SITTER_CLI} generate) {stale or ''}")
    result = tree_sitter("test", cwd=DARTDOC)
    print("\n".join("      " + l for l in result.stdout.splitlines() if "✓" in l or "✗" in l))
    check(result.returncode == 0, "its corpus passes")


def check_doc_comments(exe):
    print("== code blocks in documentation comments")
    fixture = CHECKER / "doc_comments.dart"
    out = subprocess.run([exe, "layers", str(LANGUAGES), str(fixture)], capture_output=True, text=True, check=True).stdout
    layers, errors, captures = [], [], []
    for order, line in enumerate(out.splitlines()):
        kind, *fields = line.split("\t")
        if kind == "layer":
            layers.append((int(fields[0]), fields[1], fields[2]))
        elif kind == "error":
            errors.append(fields)
        elif kind == "capture":
            row, column = map(int, fields[1].split(":"))
            captures.append((int(fields[0]), row, column, len(fields[3]), order, fields[2]))
    named = lambda name: [l for l in layers if l[1] == name]
    check([l[0] for l in named("Dartdoc")] == [1], "one Dartdoc layer, for all the /// comments")
    check([l[0] for l in named("Dartdoc Dart")] == [2, 2, 2], "a Dartdoc Dart layer for each Dart block (dart, no language, a member's), none for /** */")
    for language in ("Java", "Rust", "JavaScript", "TypeScript", "Python"):
        check([l[0] for l in named(f"Dartdoc {language}")] == [2], f"a Dartdoc {language} layer for the {language} block")
    known = {"Dart", "Dartdoc"} | {name for _, name, *_ in DOC_LANGUAGES}
    check({l[1] for l in layers} <= known and "pending" not in out.replace("pending\t1\tcomment", ""), "none for a language it has not (kotlin)")
    first = named("Dartdoc Dart")[0][2].split(",")
    check(len(first) == 6, f"the lines of a block are one layer ({len(first)} lines)")
    check(not errors, f"the blocks parse without errors {errors or ''}")
    check_marks(fixture, captures)

    stale = [str(p.relative_to(ROOT)) for p, text in doc_language_files().items() if not p.exists() or p.read_text() != text]
    check(not stale, f"the languages of examples are what --update writes {stale or ''}")
    for directory, *_ in DOC_LANGUAGES:
        check(
            sorted(p.name for p in (LANGUAGES / directory).iterdir()) == ["config.toml", "highlights.scm"],
            f"languages/{directory} has no outline, runnables or tasks",
        )
    check("hidden = true" in (LANGUAGES / "dartdoc" / "config.toml").read_text(), "languages/dartdoc is hidden")

    print("== the examples set apart in the Farum Azula themes")
    for theme in json.loads(THEMES.read_text())["themes"]:
        syntax = theme["style"]["syntax"]
        block = syntax.get("dartdoc.code", {})
        check(block.get("color") == syntax["comment.doc"]["color"], f"{theme['name']}: dartdoc.code looks like the comment")
        want = themed_doc_styles(theme)
        got = {k: v for k, v in syntax.items() if k.endswith(DOC_SUFFIX)}
        check(got == want, f"{theme['name']}: each of the {len(want)} captures of an example has its color, darkened (regenerate: --update)")


if __name__ == "__main__":
    main()
